def set_lang(code: str) -> None:
    """设置当前语言；未知代码退回中文。"""
    global _current
    _current = code if code in LANGUAGES else "zh"


def get_lang() -> str:
    return _current


def t(text: str) -> str:
    """翻译一段界面文案。

    中文模式原样返回；英文模式查表，查不到就退回原文，
    避免新增文案时界面出现空白或占位符。
    """
    if _current == "zh" or not text:
        return text
    return _EN.get(text, text)
